# frozen_string_literal: true

require "async"
require "minitest/autorun"

require_relative "asset"

class Klenod::Build::Asset::Test < Minitest::Test
  def test_static_asset_is_ready
    asset =
      Klenod::Build::Asset.new(
        "styles/home.css",
        "abc",
        "/assets/home.css",
        nil,
        "body {}",
        "text/css",
        {}
      )

    assert(asset.ready?)
    assert(asset.static?)
    refute(asset.generated?)
    refute(asset.pending?)
    refute(asset.running?)
    refute(asset.failed?)
    assert_equal("body {}", asset.bytes)
  end

  def test_generated_asset_runs_generator_once_for_concurrent_waiters
    calls = 0
    asset =
      Klenod::Build::Asset.generated(
        "images/hero.png",
        "abc",
        "/assets/hero.320w.png",
        nil,
        "image/png",
        {}
      ) do
        calls += 1
        sleep(0.01)
        "generated bytes"
      end

    refute(asset.ready?)
    assert(asset.pending?)
    assert(asset.generated?)
    refute(asset.static?)

    with_async_task do |task|
      first = task.async { asset.bytes }
      second = task.async { asset.bytes }

      assert_equal("generated bytes", first.wait)
      assert_equal("generated bytes", second.wait)
    end

    assert(asset.ready?)
    refute(asset.pending?)
    refute(asset.running?)
    assert_equal(1, calls)
  end

  def test_generated_asset_reports_running_state
    started = Async::Condition.new
    release = Async::Condition.new
    asset =
      Klenod::Build::Asset.generated(
        "images/hero.png",
        "abc",
        "/assets/hero.320w.png",
        nil,
        "image/png",
        {}
      ) do
        started.signal
        release.wait
        "generated bytes"
      end

    with_async_task do |task|
      waiter = task.async { asset.wait }

      started.wait
      assert(asset.running?)
      refute(asset.ready?)

      release.signal
      waiter.wait
    end

    assert(asset.ready?)
    refute(asset.running?)
    assert_equal("generated bytes", asset.bytes)
  end

  def test_generated_asset_records_failure
    failure = RuntimeError.new("could not generate")
    asset =
      Klenod::Build::Asset.generated(
        "images/hero.png",
        "abc",
        "/assets/hero.320w.png",
        nil,
        "image/png",
        {}
      ) do
        raise failure
      end

    error = assert_raises(RuntimeError) { asset.wait }

    assert_same(failure, error)
    assert(asset.failed?)
    assert(asset.generated?)
    refute(asset.ready?)
    refute(asset.running?)
    assert_same(failure, asset.error)
    assert_same(failure, assert_raises(RuntimeError) { asset.wait })
  end

  def test_generated_asset_failure_is_shared_by_concurrent_waiters
    calls = 0
    failure = RuntimeError.new("could not generate")
    asset =
      Klenod::Build::Asset.generated(
        "images/hero.png",
        "abc",
        "/assets/hero.320w.png",
        nil,
        "image/png",
        {}
      ) do
        calls += 1
        sleep(0.01)
        raise failure
      end

    with_async_task do |task|
      first =
        task.async do
          asset.wait
        rescue => e
          e
        end
      second =
        task.async do
          asset.wait
        rescue => e
          e
        end

      assert_same(failure, first.wait)
      assert_same(failure, second.wait)
    end

    assert(asset.failed?)
    assert_same(failure, asset.error)
    assert_equal(1, calls)
  end

  private

  def with_async_task(&block)
    enabled = Warning[:experimental]
    Warning[:experimental] = false
    Async(&block).wait
  ensure
    Warning[:experimental] = enabled
  end
end
