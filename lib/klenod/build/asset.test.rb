# frozen_string_literal: true

require "async"
require "minitest/autorun"

require_relative "asset"

class Klenod::Build::Asset::Test < Minitest::Test
  def test_static_asset_is_ready
    asset =
      Klenod::Build::Asset.new(
        "styles/home.css",
        "abc",
        "/assets/home.css",
        nil,
        "body {}",
        "text/css",
        {}
      )

    assert(asset.ready?)
    assert_equal("body {}", asset.bytes)
  end

  def test_generated_asset_runs_generator_once_for_concurrent_waiters
    calls = 0
    asset =
      Klenod::Build::Asset.generated(
        "images/hero.png",
        "abc",
        "/assets/hero.320w.png",
        nil,
        "image/png",
        {}
      ) do
        calls += 1
        sleep(0.01)
        "generated bytes"
      end

    refute(asset.ready?)
    assert(asset.pending?)

    with_async_task do |task|
      first = task.async { asset.bytes }
      second = task.async { asset.bytes }

      assert_equal("generated bytes", first.wait)
      assert_equal("generated bytes", second.wait)
    end

    assert(asset.ready?)
    assert_equal(1, calls)
  end

  private

  def with_async_task(&block)
    enabled = Warning[:experimental]
    Warning[:experimental] = false
    Async(&block).wait
  ensure
    Warning[:experimental] = enabled
  end
end
