# frozen_string_literal: true

require "json"
require "minitest/autorun"

require "klenod/build/plugins/node_modules_plugin/package_exports"

class Klenod::Build::Plugins::NodeModulesPlugin::PackageExportsTest < Minitest::Test
  PackageExports = Klenod::Build::Plugins::NodeModulesPlugin::PackageExports

  PACKAGES_DIR = File.expand_path("__test__/packages", __dir__)

  # Trimmed copies of real registry metadata, pinned to the version in each
  # file. Regenerate them when a case needs a newer package layout.
  def package(name)
    JSON.parse(File.read(File.join(PACKAGES_DIR, "#{name}.json")))
  end

  def resolve(package_json, subpath: ".", **options)
    PackageExports.resolve(package_json, subpath: subpath, **options)
  end

  def assert_resolves(expected, package_json, subpath: ".", **options)
    result = resolve(package_json, subpath: subpath, **options)

    assert result.resolved?, "expected #{subpath.inspect} to resolve, got #{result.reason}: #{result.message}"
    assert_equal expected, result.path
  end

  def assert_unresolved(reason, package_json, subpath: ".", **options)
    result = resolve(package_json, subpath: subpath, **options)

    refute result.resolved?, "expected #{subpath.inspect} not to resolve, got #{result.path.inspect}"
    assert_equal reason, result.reason
    refute_empty result.message
    result
  end

  # Real packages.

  def test_falls_back_to_the_module_field_when_a_package_has_no_exports
    # gl-matrix 3.4.4 ships "main": "cjs/index.js" and "module": "esm/index.js"
    # with no exports field at all, so the legacy fallback decides whether we
    # get the ES module or the CommonJS build.
    assert_resolves "esm/index.js", package("gl-matrix")
  end

  def test_treats_a_subpath_as_a_file_path_when_a_package_has_no_exports
    assert_resolves "esm/vec3.js", package("gl-matrix"), subpath: "./esm/vec3.js"
  end

  def test_resolves_three_core_to_its_prebundled_es_module
    assert_resolves "build/three.module.js", package("three")
  end

  def test_resolves_a_three_addon_through_a_wildcard_subpath
    assert_resolves(
      "examples/jsm/controls/OrbitControls.js",
      package("three"),
      subpath: "./addons/controls/OrbitControls.js"
    )
  end

  def test_prefers_an_exact_subpath_over_a_wildcard_that_also_matches
    assert_resolves "examples/jsm/Addons.js", package("three"), subpath: "./addons"
  end

  def test_resolves_a_plain_string_subpath_target
    assert_resolves "build/three.tsl.js", package("three"), subpath: "./tsl"
  end

  def test_skips_the_types_condition_and_falls_through_to_default
    assert_resolves "index.js", package("lit")
    assert_resolves "decorators/custom-element.js", package("lit"), subpath: "./decorators/custom-element.js"
  end

  def test_matches_conditions_in_package_json_key_order
    # preact lists umd, types, import, browser, require in that order. "browser"
    # is one of our conditions but appears after "import", so key order rather
    # than the order of DEFAULT_CONDITIONS decides the winner.
    assert_resolves "dist/preact.mjs", package("preact")
    assert_resolves "hooks/dist/hooks.mjs", package("preact"), subpath: "./hooks"
  end

  def test_ignores_unknown_vendor_conditions
    # zod offers a "@zod/source" condition pointing at TypeScript sources.
    assert_resolves "index.js", package("zod")
    assert_resolves "mini/index.js", package("zod"), subpath: "./mini"
  end

  def test_resolves_nested_conditions_in_a_scoped_package
    # @lit/reactive-element nests conditions two deep and lists "node" before
    # "browser", so the browser build is only reached by respecting key order
    # and then recursing.
    assert_resolves "reactive-element.js", package("lit-reactive-element")
    assert_resolves "css-tag.js", package("lit-reactive-element"), subpath: "./css-tag.js"
  end

  def test_resolves_the_node_build_when_node_conditions_are_requested
    assert_resolves(
      "node/reactive-element.js",
      package("lit-reactive-element"),
      conditions: ["node", "default"]
    )
  end

  def test_reports_available_subpaths_when_a_subpath_is_missing
    result = assert_unresolved(:no_match, package("three"), subpath: "./nope")

    assert_includes result.message, "./tsl"
  end

  # Subpath normalization.

  def test_normalizes_equivalent_subpath_spellings
    metadata = {"exports" => {"." => "./index.js", "./hooks" => "./hooks.js"}}

    ["hooks", "./hooks", "/hooks"].each do |subpath|
      assert_resolves "hooks.js", metadata, subpath: subpath
    end

    ["", ".", "./"].each do |subpath|
      assert_resolves "index.js", metadata, subpath: subpath
    end
  end

  # exports shapes.

  def test_resolves_exports_given_as_a_string
    assert_resolves "index.js", {"exports" => "./index.js"}
  end

  def test_resolves_a_bare_condition_object_as_the_root_subpath
    metadata = {"exports" => {"import" => "./index.mjs", "require" => "./index.cjs"}}

    assert_resolves "index.mjs", metadata
    assert_unresolved :no_match, metadata, subpath: "./hooks"
  end

  def test_resolves_nested_conditions
    metadata = {"exports" => {"." => {"browser" => {"import" => "./browser.mjs"}, "default" => "./index.js"}}}

    assert_resolves "browser.mjs", metadata
  end

  def test_resolves_the_first_usable_entry_of_an_array_target
    metadata = {"exports" => {"." => [nil, "./index.js"]}}

    assert_resolves "index.js", metadata
  end

  def test_honours_a_custom_condition_set
    metadata = {"exports" => {"." => {"import" => "./index.mjs", "custom" => "./custom.js"}}}

    assert_resolves "custom.js", metadata, conditions: ["custom"]
  end

  # Failure modes.

  def test_reports_commonjs_only_packages
    metadata = {"exports" => {"." => {"require" => "./index.cjs", "types" => "./index.d.ts"}}}
    result = assert_unresolved(:commonjs_only, metadata)

    assert_includes result.message, "CommonJS"
  end

  def test_reports_a_blocked_subpath
    metadata = {"exports" => {"." => "./index.js", "./internal" => nil}}

    assert_unresolved :blocked, metadata, subpath: "./internal"
  end

  def test_reports_a_subpath_blocked_by_an_explicit_null_condition
    metadata = {"exports" => {"." => {"import" => nil, "default" => "./index.js"}}}

    assert_unresolved :blocked, metadata
  end

  def test_reports_when_no_condition_matches
    metadata = {"exports" => {"." => {"deno" => "./deno.js", "types" => "./index.d.ts"}}}
    result = assert_unresolved(:conditions_unmet, metadata)

    assert_includes result.message, "deno"
  end

  def test_rejects_a_target_that_escapes_the_package
    assert_unresolved :invalid, {"exports" => {"." => "../outside.js"}}
  end

  def test_rejects_a_wildcard_target_reached_without_a_pattern
    assert_unresolved :invalid, {"exports" => {"." => "./dist/*.js"}}
  end

  def test_rejects_exports_that_mixes_subpaths_and_conditions
    result = assert_unresolved(:invalid, {"exports" => {"." => "./index.js", "import" => "./index.mjs"}})

    assert_includes result.message, "import"
  end

  def test_rejects_metadata_that_is_not_an_object
    assert_unresolved :invalid, "nope"
  end

  # Wildcard matching.

  def test_prefers_the_pattern_with_the_longest_prefix
    metadata = {"exports" => {"./*" => "./generic/*", "./deep/*" => "./specific/*"}}

    assert_resolves "specific/file.js", metadata, subpath: "./deep/file.js"
    assert_resolves "generic/other.js", metadata, subpath: "./other.js"
  end

  def test_breaks_prefix_ties_on_the_longest_suffix
    metadata = {"exports" => {"./*" => "./any/*", "./*.js" => "./scripts/*.js"}}

    assert_resolves "scripts/main.js", metadata, subpath: "./main.js"
  end

  def test_substitutes_every_wildcard_in_a_target
    metadata = {"exports" => {"./*" => "./dist/*/*.js"}}

    assert_resolves "dist/card/card.js", metadata, subpath: "./card"
  end

  def test_requires_a_pattern_match_to_be_non_overlapping
    metadata = {"exports" => {"./prefix-*-suffix" => "./out/*.js"}}

    assert_resolves "out/name.js", metadata, subpath: "./prefix-name-suffix"
    assert_unresolved :no_match, metadata, subpath: "./prefix-suffix"
  end

  # Private "#" imports.

  def private_imports
    {
      "imports" => {
        "#internal/*" => "./src/internal/*.js",
        "#helper" => "helper-package",
        "#scoped" => "@scope/pkg/sub.js",
        "#platform" => {"browser" => "./src/browser.js", "node" => "./src/node.js"},
        "#nodeonly" => {"node" => "./src/node.js"},
        "#blocked" => nil,
        "#escape" => "../outside.js"
      }
    }
  end

  def resolve_private(specifier, package_json: private_imports, **options)
    PackageExports.resolve_private(package_json, specifier: specifier, **options)
  end

  def assert_private(expected, specifier, **options)
    result = resolve_private(specifier, **options)

    assert result.resolved?, "expected #{specifier.inspect} to resolve, got #{result.reason}: #{result.message}"
    assert_equal expected, result.path
  end

  # A target inside the package keeps its "./" so the caller can tell it apart
  # from a bare specifier naming another package.
  def test_keeps_the_dot_slash_prefix_on_an_internal_private_import
    assert_private "./src/internal/secret.js", "#internal/secret"
    assert_private "./src/browser.js", "#platform"
  end

  def test_returns_a_bare_specifier_for_a_private_import_naming_another_package
    assert_private "helper-package", "#helper"
    assert_private "@scope/pkg/sub.js", "#scoped"
  end

  def test_reports_a_private_import_that_escapes_the_package
    result = resolve_private("#escape")

    assert_equal :invalid, result.reason
    assert_includes result.message, "must stay within the package"
  end

  def test_reports_a_blocked_private_import
    assert_equal :blocked, resolve_private("#blocked").reason
  end

  # "node" is not a module system, so a node-only target is an unmatched
  # condition rather than a CommonJS entry.
  def test_reports_a_node_only_private_import_as_an_unmatched_condition
    result = resolve_private("#nodeonly")

    assert_equal :conditions_unmet, result.reason
    assert_includes result.message, "node"
  end

  def test_reports_an_undefined_private_import
    result = resolve_private("#nope")

    assert_equal :no_match, result.reason
    assert_includes result.message, "#helper"
  end

  def test_rejects_specifiers_that_are_not_private_imports
    ["#", "#/x", "helper", "./x.js"].each do |specifier|
      assert_equal :invalid, resolve_private(specifier).reason, specifier
    end
  end

  def test_reports_a_package_with_no_imports_field
    result = resolve_private("#x", package_json: {"name" => "bare"})

    assert_equal :no_match, result.reason
    assert_includes result.message, "no imports field"
  end

  def test_matches_a_custom_condition_in_a_private_import
    assert_private "./src/node.js", "#platform", conditions: ["node"]
  end

  # Legacy fallback ordering.

  def test_prefers_module_over_main
    assert_resolves "esm.js", {"module" => "esm.js", "main" => "cjs.js"}
  end

  def test_falls_back_to_index_js_when_no_entry_field_is_present
    assert_resolves "index.js", {"name" => "bare"}
  end

  def test_ignores_an_empty_entry_field
    assert_resolves "cjs.js", {"module" => "", "main" => "cjs.js"}
  end

  def test_strips_a_leading_dot_slash_from_legacy_entry_fields
    assert_resolves "build/three.module.js", {"module" => "./build/three.module.js"}
  end
end
