  def test_prefers_a_nested_dependency_over_the_hoisted_one
    with_project do |dir|
      # Both copies exist. Only needs-helper resolves the name, so the nearest
      # node_modules has to win without the duplicate check firing.
      package(dir, "helper-package", {"module" => "index.js"}, under: "needs-helper", version: "2.0.0") do |root|
        write(root, "index.js", "export const value = 'nested';\n")
      end
      write_entry(dir, %(import { value } from "npm://needs-helper";\nconsole.log(value);\n))

      context = context_for(dir)
      context.evaluate("app.js")

      asset = javascript_asset(context, "npm://helper-package/index.js")

      assert_includes asset.bytes, "nested"
    end
  end

