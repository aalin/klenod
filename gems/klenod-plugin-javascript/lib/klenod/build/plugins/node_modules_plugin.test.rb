# frozen_string_literal: true

require "fileutils"
require "json"
require "minitest/autorun"
require "tmpdir"

require "klenod/plugin/javascript"

class Klenod::Build::Plugins::NodeModulesPlugin::Test < Minitest::Test
  ResolveError = Klenod::Build::ResolveError

  def test_namespace_constructs_the_plugin
    assert_instance_of Klenod::Build::Plugins::NodeModulesPlugin::Plugin, Klenod::Build::Plugins::NodeModulesPlugin.new
  end

  def test_resolves_a_package_without_exports_through_its_module_field
    with_project do |dir|
      write_entry(dir, <<~JS)
        import { vec3 } from "npm://gl-matrix";
        console.log(vec3);
      JS

      context = context_for(dir)
      context.evaluate("app.js")

      assert_includes npm_logical_names(context), "npm://gl-matrix/esm/index.js"
    end
  end

  def test_never_loads_the_commonjs_build_of_a_dual_package
    with_project do |dir|
      write_entry(dir, %(import { vec3 } from "npm://gl-matrix";\nconsole.log(vec3);\n))

      context = context_for(dir)
      context.evaluate("app.js")

      refute_includes npm_logical_names(context), "npm://gl-matrix/cjs/index.js"
    end
  end

  def test_follows_relative_imports_inside_a_package
    with_project do |dir|
      write_entry(dir, %(import { vec3 } from "npm://gl-matrix";\nconsole.log(vec3);\n))

      context = context_for(dir)
      context.evaluate("app.js")

      assert_equal(
        ["npm://gl-matrix/esm/common.js", "npm://gl-matrix/esm/index.js", "npm://gl-matrix/esm/vec3.js"],
        npm_logical_names(context).sort
      )
    end
  end

  def test_rewrites_an_npm_import_to_a_hashed_asset_url
    with_project do |dir|
      write_entry(dir, %(import { vec3 } from "npm://gl-matrix";\nconsole.log(vec3);\n))

      context = context_for(dir)
      context.evaluate("app.js")

      entry = javascript_asset(context, "app.js")
      package = javascript_asset(context, "npm://gl-matrix/esm/index.js")

      assert_match(%r{\A/assets/npm_gl_matrix_esm_index_js\.[a-f0-9]{16}\.js\z}, package.url)
      assert_match(/from\s*["']#{Regexp.escape(package.url)}["']/, entry.bytes)
      refute_includes entry.bytes, "npm://gl-matrix"
    end
  end

  def test_resolves_a_package_entry_through_the_import_condition
    with_project do |dir|
      write_entry(dir, %(import * as THREE from "npm://three";\nconsole.log(THREE);\n))

      context = context_for(dir)
      context.evaluate("app.js")

      assert_includes npm_logical_names(context), "npm://three/build/three.module.js"
      refute_includes npm_logical_names(context), "npm://three/build/three.cjs"
    end
  end

  def test_resolves_a_subpath_through_a_wildcard_export
    with_project do |dir|
      write_entry(dir, <<~JS)
        import { OrbitControls } from "npm://three/addons/controls/OrbitControls.js";
        console.log(OrbitControls);
      JS

      context = context_for(dir)
      context.evaluate("app.js")

      assert_includes npm_logical_names(context), "npm://three/examples/jsm/controls/OrbitControls.js"
    end
  end

  def test_resolves_a_scoped_package
    with_project do |dir|
      write_entry(dir, %(import widget from "npm://@scope/widget";\nconsole.log(widget);\n))

      context = context_for(dir)
      context.evaluate("app.js")

      assert_includes npm_logical_names(context), "npm://@scope/widget/index.js"
    end
  end

  def test_resolves_a_scoped_package_subpath
    with_project do |dir|
      write_entry(dir, %(import helper from "npm://@scope/widget/helper.js";\nconsole.log(helper);\n))

      context = context_for(dir)
      context.evaluate("app.js")

      assert_includes npm_logical_names(context), "npm://@scope/widget/helper.js"
    end
  end

  def test_shares_one_module_between_packages_imported_twice
    with_project do |dir|
      write_entry(dir, %(import "./one.js";\nimport "./two.js";\n))
      File.write("#{dir}/src/one.js", %(import { vec3 } from "npm://gl-matrix";\nexport default vec3;\n))
      File.write("#{dir}/src/two.js", %(import { vec3 } from "npm://gl-matrix";\nexport default vec3;\n))

      context = context_for(dir)
      context.evaluate("app.js")

      assert_equal 1, npm_logical_names(context).count { it == "npm://gl-matrix/esm/index.js" }
    end
  end

  def test_accepts_an_explicit_node_modules_root
    with_project do |dir|
      moved = File.join(dir, "vendor")
      FileUtils.mkdir_p(moved)
      FileUtils.mv(File.join(dir, "node_modules"), File.join(moved, "node_modules"))
      write_entry(dir, %(import { vec3 } from "npm://gl-matrix";\nconsole.log(vec3);\n))

      plugin = Klenod::Build::Plugins::NodeModulesPlugin.new(root: File.join(moved, "node_modules"))
      context = context_for(dir, node_modules_plugin: plugin)
      context.evaluate("app.js")

      assert_includes npm_logical_names(context), "npm://gl-matrix/esm/index.js"
    end
  end

  # Failure modes.

  def test_reports_a_commonjs_only_package
    error = assert_npm_error(%(import x from "npm://legacy";\nconsole.log(x);\n))

    assert_match(/CommonJS/, error.message)
  end

  def test_reports_a_package_that_is_not_installed
    error = assert_npm_error(%(import x from "npm://missing";\nconsole.log(x);\n))

    assert_match(/Is it installed\?/, error.message)
  end

  def test_reports_a_missing_file_inside_a_package
    error = assert_npm_error(%(import x from "npm://gl-matrix/esm/nope.js";\nconsole.log(x);\n))

    assert_match(/has no file at esm\/nope\.js/, error.message)
  end

  def test_reports_a_subpath_a_package_does_not_export
    error = assert_npm_error(%(import x from "npm://three/nope";\nconsole.log(x);\n))

    assert_match(/does not export/, error.message)
  end

  def test_reports_a_bare_import_between_packages
    error = assert_npm_error(%(import x from "npm://needs-tslib";\nconsole.log(x);\n))

    assert_match(/Imports between npm packages are not supported yet/, error.message)
  end

  # URL joining clamps at the authority, so "../../outside.js" collapses to the
  # package root rather than reaching a sibling package. The import fails as a
  # missing file, and assert_inside_package! stays as defence in depth.
  def test_reports_a_relative_import_that_climbs_out_of_its_package
    error = assert_npm_error(%(import x from "npm://escaper";\nconsole.log(x);\n))

    assert_match(%r{escaper has no file at outside\.js}, error.message)
    refute_match(/node_modules\/outside\.js/, error.message)
  end

  private

  def assert_npm_error(source)
    with_project do |dir|
      write_entry(dir, source)
      context = context_for(dir)

      assert_raises(ResolveError) { context.evaluate("app.js") }
    end
  end

  def write_entry(dir, source)
    File.write("#{dir}/src/app.js", source)
  end

  # Package metadata mirrors the real registry layouts these cases exist for.
  def with_project(&block)
    Dir.mktmpdir do |dir|
      FileUtils.mkdir_p("#{dir}/src")

      # gl-matrix 3.4.4: no exports field, dual main/module entries.
      package(dir, "gl-matrix", {"main" => "cjs/index.js", "module" => "esm/index.js"}) do |root|
        write(root, "esm/index.js", <<~JS)
          import * as glMatrix from "./common.js";
          import * as vec3 from "./vec3.js";
          export { glMatrix, vec3 };
        JS
        write(root, "esm/common.js", "export const EPSILON = 0.000001;\n")
        write(root, "esm/vec3.js", %(import { EPSILON } from "./common.js";\nexport const create = () => EPSILON;\n))
        write(root, "cjs/index.js", "module.exports = require('./vec3.js');\n")
      end

      # three 0.186.0: condition map plus wildcard addon subpaths.
      three_exports = {
        "." => {"import" => "./build/three.module.js", "require" => "./build/three.cjs"},
        "./addons" => "./examples/jsm/Addons.js",
        "./addons/*" => "./examples/jsm/*"
      }
      package(dir, "three", {"type" => "module", "exports" => three_exports}) do |root|
        write(root, "build/three.module.js", "export const REVISION = '186';\n")
        write(root, "build/three.cjs", "module.exports = {};\n")
        write(root, "examples/jsm/Addons.js", %(export * from "./controls/OrbitControls.js";\n))
        write(root, "examples/jsm/controls/OrbitControls.js", "export const OrbitControls = class {};\n")
      end

      package(dir, "@scope/widget", {"module" => "index.js"}) do |root|
        write(root, "index.js", "export default 'widget';\n")
        write(root, "helper.js", "export default 'helper';\n")
      end

      package(dir, "legacy", {"exports" => {"." => {"require" => "./index.cjs"}}}) do |root|
        write(root, "index.cjs", "module.exports = {};\n")
      end

      package(dir, "needs-tslib", {"module" => "index.js"}) do |root|
        write(root, "index.js", %(import { __extends } from "tslib";\nexport default __extends;\n))
      end

      package(dir, "escaper", {"module" => "index.js"}) do |root|
        write(root, "index.js", %(export { default } from "../../outside.js";\n))
      end

      block.call(dir)
    end
  end

  def package(dir, name, metadata)
    root = File.join(dir, "node_modules", name)
    FileUtils.mkdir_p(root)
    File.write(File.join(root, "package.json"), JSON.generate({"name" => name, "version" => "1.0.0"}.merge(metadata)))
    yield(root) if block_given?
  end

  def write(root, relative_path, source)
    path = File.join(root, relative_path)
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, source)
  end

  def context_for(dir, node_modules_plugin: Klenod::Build::Plugins::NodeModulesPlugin.new)
    Klenod::Build::Context.new(
      source_dir: File.join(dir, "src"),
      mode: :development,
      base: "/assets/",
      plugins: [
        *Klenod::Build::Context.default_plugins,
        node_modules_plugin,
        Klenod::Build::Plugins::JavaScriptPlugin.new
      ]
    )
  end

  def javascript_assets(context)
    context.graph.each_asset.select { it.metadata[:type] == :javascript }
  end

  def javascript_asset(context, logical_name)
    javascript_assets(context).find { it.logical_name == logical_name } || flunk("Missing asset for #{logical_name}")
  end

  def npm_logical_names(context)
    javascript_assets(context).map(&:logical_name).select { it.start_with?("npm://") }
  end
end
